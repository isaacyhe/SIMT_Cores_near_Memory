#!/usr/bin/env python3
"""
Comprehensive Verilog fixer for OpenROAD compatibility.
Fixes escaped identifiers generated by Yosys flatten.

Usage: python3 fix_verilog.py input.v output.v
"""

import re
import sys

def fix_verilog(content):
    """
    Systematically fix all escaped identifier issues for OpenROAD.
    """
    lines = content.split('\n')
    fixed_lines = []

    for line_num, line in enumerate(lines, 1):
        original = line

        # Skip comments
        if line.strip().startswith('//'):
            fixed_lines.append(line)
            continue

        # Pattern 1: Escaped identifiers with backslash
        # \identifier.sub[0].name -> identifier_sub_0__name
        # The escaped identifier starts with \ and ends at whitespace
        def fix_escaped(match):
            name = match.group(1)
            # Replace dots with underscores
            name = name.replace('.', '_')
            # Replace [N] with _N_
            name = re.sub(r'\[(\d+)\]', r'_\1_', name)
            # Clean up multiple underscores
            name = re.sub(r'_+', '_', name)
            # Remove trailing underscore before space/semicolon
            name = name.rstrip('_')
            return name

        # Match \escaped_identifier (ends at space, semicolon, comma, paren, bracket, or equals)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*)\s', lambda m: fix_escaped(m) + ' ', line)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*);', lambda m: fix_escaped(m) + ';', line)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*),', lambda m: fix_escaped(m) + ',', line)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*)\)', lambda m: fix_escaped(m) + ')', line)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*)\]', lambda m: fix_escaped(m) + ']', line)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*)\(', lambda m: fix_escaped(m) + '(', line)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*)=', lambda m: fix_escaped(m) + '=', line)

        # Pattern 2: Any remaining backslash-escaped identifiers (aggressive)
        line = re.sub(r'\\([a-zA-Z_][a-zA-Z0-9_.\[\]]*)', fix_escaped, line)

        # Pattern 3: Unescaped dots in identifiers (signal.subsignal)
        # But NOT in module instantiation port connections (.port(signal))
        # And NOT in numbers (1.5)

        # First protect port connections: .port( -> PROTECT_port(
        protected = {}
        def protect_port(m):
            key = f"__PROTECT_{len(protected)}__"
            protected[key] = m.group(0)
            return key
        line = re.sub(r'\.([a-zA-Z_][a-zA-Z0-9_]*)\s*\(', protect_port, line)

        # Now fix remaining dots between identifiers
        # identifier.identifier -> identifier_identifier
        prev_line = ""
        while prev_line != line:
            prev_line = line
            line = re.sub(r'([a-zA-Z0-9_])\.([$a-zA-Z_])', r'\1_\2', line)

        # Restore protected port connections
        for key, val in protected.items():
            line = line.replace(key, val)

        # Pattern 4: Brackets in identifier names (not array indices)
        # g_clusters[0]_name -> g_clusters_0_name
        # But preserve wire [31:0] declarations

        # Don't touch lines that are just wire/reg declarations with bit widths
        if not re.match(r'\s*(wire|reg|input|output|inout)\s*\[\d+:\d+\]', line):
            # Fix identifier[N]identifier patterns
            line = re.sub(r'([a-zA-Z_][a-zA-Z0-9_]*)\[(\d+)\]([_a-zA-Z])', r'\1_\2_\3', line)
            # Fix identifier[N] at end of name (before space/semicolon)
            line = re.sub(r'([a-zA-Z_][a-zA-Z0-9_]*)\[(\d+)\](\s|;|,|\))', r'\1_\2_\3', line)

        # Pattern 5: Dollar signs anywhere in identifiers ($func$, $paramod, etc.)
        # Replace $ with _ throughout
        line = re.sub(r'\$', '_', line)

        # Pattern 6: Colons in identifiers (project_v:23826 -> project_v_23826)
        # But preserve bit ranges like [31:0]
        # Replace colons that are NOT inside brackets
        line = re.sub(r'([a-zA-Z0-9_]):([0-9])', r'\1_\2', line)

        # Pattern 7: Clean up any triple+ underscores
        line = re.sub(r'_{3,}', '__', line)

        # Pattern 8: Fix __ at start of identifier (invalid)
        line = re.sub(r'(\s)__([a-zA-Z])', r'\1_\2', line)

        fixed_lines.append(line)

    return '\n'.join(fixed_lines)


def main():
    if len(sys.argv) < 2:
        print("Usage: python3 fix_verilog.py input.v [output.v]")
        print("If output.v not specified, overwrites input.v")
        sys.exit(1)

    input_file = sys.argv[1]
    output_file = sys.argv[2] if len(sys.argv) > 2 else input_file

    print(f"Reading: {input_file}")
    with open(input_file, 'r') as f:
        content = f.read()

    original_size = len(content)

    # Count issues before
    escaped_before = len(re.findall(r'\\[a-zA-Z]', content))
    dots_before = len(re.findall(r'[a-zA-Z0-9_]\.[a-zA-Z_]', content))

    print(f"  Original: {original_size} bytes")
    print(f"  Escaped identifiers: {escaped_before}")
    print(f"  Dots in identifiers: {dots_before}")

    # Fix
    fixed = fix_verilog(content)

    # Count issues after
    escaped_after = len(re.findall(r'\\[a-zA-Z]', fixed))
    dots_after = len(re.findall(r'[a-zA-Z0-9_]\.[a-zA-Z_]', fixed))

    print(f"Writing: {output_file}")
    with open(output_file, 'w') as f:
        f.write(fixed)

    print(f"  Fixed: {len(fixed)} bytes")
    print(f"  Escaped identifiers: {escaped_before} -> {escaped_after}")
    print(f"  Dots in identifiers: {dots_before} -> {dots_after}")

    if escaped_after > 0 or dots_after > 0:
        print("\nWARNING: Some issues may remain. Check the output file.")
        # Show first few remaining issues
        lines = fixed.split('\n')
        print("\nRemaining escaped identifiers:")
        count = 0
        for i, line in enumerate(lines, 1):
            if '\\' in line and re.search(r'\\[a-zA-Z]', line):
                print(f"  Line {i}: {line[:100]}...")
                count += 1
                if count >= 5:
                    break

    return 0 if (escaped_after == 0 and dots_after == 0) else 1


if __name__ == '__main__':
    sys.exit(main())
